"""AI-usage ledger: an append-only record of every model call, and the disclosure report built from it.

Contests that allow AI assistance (Jane Street x Tiny Tapeout does) ask you to say how it was used. The ledger makes
that answer a measurement instead of a recollection. Each line records metadata only (model, stage, tokens, a hash of
the prompt), never prompt or response text, so a ledger is safe to commit.

Scope, stated plainly in the report: the ledger sees calls routed through SiliconForge. It cannot see anything you
typed into another tool, so the report says so and leaves a section for the human to complete.
"""
from __future__ import annotations

import hashlib
import json
import threading
import time
from collections import Counter, defaultdict
from pathlib import Path


def prompt_hash(system_prompt: str, user_prompt: str) -> str:
    return hashlib.sha256(f"{system_prompt}\x00{user_prompt}".encode()).hexdigest()[:16]


class Ledger:
    def __init__(self, path: str | Path) -> None:
        self.path = Path(path)
        self._lock = threading.Lock()

    def record(self, *, stage: str, task: str, tier: str, provider: str, model: str, prompt_tokens: int,
               completion_tokens: int, cached_tokens: int, latency_s: float, billing: str, cache_hit: bool,
               phash: str, run_id: str | None = None) -> None:
        row = {
            "ts": round(time.time(), 3), "run_id": run_id, "stage": stage, "task": task, "tier": tier,
            "provider": provider, "model": model, "prompt_tokens": prompt_tokens,
            "completion_tokens": completion_tokens, "cached_tokens": cached_tokens, "latency_s": latency_s,
            "billing": billing, "cache_hit": cache_hit, "prompt_sha": phash,
        }
        with self._lock:
            self.path.parent.mkdir(parents=True, exist_ok=True)
            with self.path.open("a", encoding="utf-8") as f:
                f.write(json.dumps(row) + "\n")

    def rows(self) -> list[dict]:
        return read_ledger(self.path)


def read_ledger(path: str | Path) -> list[dict]:
    p = Path(path)
    if not p.exists():
        return []
    rows = []
    for line in p.read_text(encoding="utf-8").splitlines():
        try:
            rows.append(json.loads(line))
        except json.JSONDecodeError:
            continue  # a torn final line from a crash must not hide the rest
    return rows


def summarize(rows: list[dict]) -> dict:
    live = [r for r in rows if not r.get("cache_hit")]
    by_model: dict[str, dict] = defaultdict(lambda: {"calls": 0, "prompt_tokens": 0, "completion_tokens": 0})
    for r in live:
        m = by_model[f"{r['provider']}:{r['model']}"]
        m["calls"] += 1
        m["prompt_tokens"] += r.get("prompt_tokens", 0)
        m["completion_tokens"] += r.get("completion_tokens", 0)
    stages = Counter(r.get("stage", "?") for r in live)
    return {
        "calls": len(live), "cache_hits": len(rows) - len(live), "models": dict(by_model), "stages": dict(stages),
        "first_ts": min((r["ts"] for r in rows), default=None), "last_ts": max((r["ts"] for r in rows), default=None),
        "prompt_tokens": sum(r.get("prompt_tokens", 0) for r in live),
        "completion_tokens": sum(r.get("completion_tokens", 0) for r in live),
    }


def render_report(rows: list[dict], *, project: str = "", allowed_models: list[str] | None = None) -> str:
    s = summarize(rows)
    fmt = lambda ts: time.strftime("%Y-%m-%d", time.gmtime(ts)) if ts else "n/a"  # noqa: E731
    out = [f"# AI usage disclosure{f' for {project}' if project else ''}", ""]
    out.append(f"Generated by `siliconforge report ai-usage` from the project's call ledger "
               f"({fmt(s['first_ts'])} to {fmt(s['last_ts'])}).")
    out += ["", "## Policy", ""]
    if allowed_models:
        out.append("Model calls were restricted by a workspace policy, enforced in code by the router: only "
                   + ", ".join(f"`{m}`" for m in allowed_models) + " could be used. Any other model in a routing "
                   "profile was dropped before a request was made.")
    else:
        out.append("No model restriction was configured for this workspace.")
    out += ["", "## What the ledger measured", "",
            f"- Model calls: **{s['calls']}** ({s['cache_hits']} further answers were replayed from the local cache "
            "and did not reach a model)",
            f"- Tokens: {s['prompt_tokens']:,} in, {s['completion_tokens']:,} out. Calls through the Antigravity CLI "
            "include roughly 10k tokens of agent overhead each, so input counts are larger than the prompts alone."]
    if s["models"]:
        out += ["", "| Model | Calls | Input tokens | Output tokens |", "|---|---:|---:|---:|"]
        for name, m in sorted(s["models"].items()):
            out.append(f"| `{name}` | {m['calls']} | {m['prompt_tokens']:,} | {m['completion_tokens']:,} |")
    if s["stages"]:
        out += ["", "Calls by pipeline stage: " + ", ".join(f"{k} ({v})" for k, v in sorted(s["stages"].items())) + "."]
    out += ["", "## What the ledger cannot see", "",
            "Only calls routed through SiliconForge are recorded: no prompt or response text is stored, just metadata "
            "and a hash. Anything done in another tool is outside it. Complete the sections below by hand.",
            "", "## Human-written section (complete before submitting)", "",
            "- Which parts of the design, tests and documents were written or edited by a person:",
            "- Which AI-generated parts were rejected or rewritten, and what caught the problem (tool output, a failing "
            "test, a formal counterexample, review):",
            "- What was verified independently of the AI that produced it:", ""]
    return "\n".join(out)

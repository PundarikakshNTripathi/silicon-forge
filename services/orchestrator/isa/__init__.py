"""ISA toolchain: one `isa.yaml` -> assembler, disassembler, Verilog decoder, golden model, docs, timing checker."""
from __future__ import annotations

import json
import re
from pathlib import Path

import yaml

from services.orchestrator.isa.asm import (
    AsmError,
    Assembler,
    Program,
    decode,
    disassemble,
    disassemble_word,
)
from services.orchestrator.isa.gen import (
    decoder_formal,
    encoding_svg,
    isa_markdown,
    verilog_decoder,
    verilog_header,
)
from services.orchestrator.isa.model import IllegalInstruction, Machine
from services.orchestrator.isa.spec import IsaError, IsaSpec, load_spec, parse_spec
from services.orchestrator.isa.timing import TimingReport, check_timing, static_gaps, trace_gaps

_HERE = Path(__file__).parent
_IMPORT = re.compile(r"^from services\.orchestrator\.isa\.\w+ import (?:\([^)]*\)|.*)$", re.MULTILINE)


def bundle_source(spec_path: str | Path) -> str:
    """A single dependency-free Python file with the spec, assembler, golden model and timing checker inside.

    It is what a project's cocotb tests and CI import, so they do not need SiliconForge installed. Only the standard
    library is used (the YAML spec is embedded as JSON)."""
    raw = yaml.safe_load(Path(spec_path).read_text(encoding="utf-8"))
    parse_spec(raw)  # refuse to bundle a broken spec
    parts = ['"""Generated by `siliconforge isa gen`: assembler, golden model and timing checker for this ISA.\n\n'
             'Standard library only. Do not edit; regenerate from isa.yaml."""\nfrom __future__ import annotations\n\nimport json\n']
    for mod in ("spec", "asm", "model", "timing"):
        text = (_HERE / f"{mod}.py").read_text(encoding="utf-8")
        text = text.replace("from __future__ import annotations\n", "")
        text = _IMPORT.sub("", text)
        if mod == "spec":
            text = text.replace("import yaml\n", "")
            text = text[: text.index("def load_spec")]
        # drop each module's docstring so the bundle has one header
        text = re.sub(r'^"""[\s\S]*?"""\n', "", text, count=1)
        parts.append(f"\n# ---------------------------------------------------------------- {mod}\n{text}")
    parts.append(f"\nSPEC_DICT = json.loads({json.dumps(json.dumps(raw))})\n\n\n"
                 "def load() -> IsaSpec:\n    return parse_spec(SPEC_DICT)\n\n\n"
                 "def assemble(source: str) -> Program:\n    return Assembler(load()).assemble(source)\n")
    return "".join(parts)


def generate_all(spec_path: str | Path, out_dir: str | Path) -> list[Path]:
    """Write every derived artifact; returns the files written."""
    spec = load_spec(spec_path)
    out = Path(out_dir)
    files: dict[Path, str] = {
        out / "rtl" / f"{spec.name}_isa.vh": verilog_header(spec),
        out / "rtl" / f"{spec.name}_decode.v": verilog_decoder(spec),
        out / "tools" / f"{spec.name}_isa.py": bundle_source(spec_path),
        out / "docs" / "isa.md": isa_markdown(spec),
    }
    sv, sby = decoder_formal(spec)
    files[out / "formal" / f"{spec.name}_decode_check.sv"] = sv
    files[out / "formal" / f"{spec.name}_decode.sby"] = sby
    for i in spec.instructions:
        files[out / "docs" / "isa" / f"{i.name}.svg"] = encoding_svg(spec, i)
    written = []
    for path, text in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        written.append(path)
    # the decoder lives beside the formal harness so `sby` finds both sources
    (out / "formal" / f"{spec.name}_decode.v").write_text(files[out / "rtl" / f"{spec.name}_decode.v"],
                                                         encoding="utf-8", newline="\n")
    written.append(out / "formal" / f"{spec.name}_decode.v")
    return written



_HERE = Path(__file__).parent
#: plain single-line imports of the standard library, which the bundle hoists to its top
_STD_IMPORT = re.compile(r"^(?:import \w[\w.]*|from (?!services)[\w.]+ import [^(\n]+)$", re.MULTILINE)
#: imports of sibling modules, which disappear in the bundle (everything lives in one file)
_SIBLING_IMPORT = re.compile(r"^from services\.orchestrator\.isa\.\w+ import (?:\([^)]*\)|.*)$", re.MULTILINE)
_DOCSTRING = re.compile(r'^"""[\s\S]*?"""\n', re.MULTILINE)
_BUNDLE_MODULES = ("spec", "asm", "model", "randprog", "timing")


def bundle_source(spec_path: str | Path) -> str:
    """A single dependency-free Python file with the spec, assembler, golden model and timing checker inside.

    It is what a project's cocotb tests and CI import, so they do not need SiliconForge installed. Only the standard
    library is used (the YAML spec is embedded as JSON), and the imports are hoisted so the file is ordinary clean Python.
    """
    raw = yaml.safe_load(Path(spec_path).read_text(encoding="utf-8"))
    parse_spec(raw)  # refuse to bundle a broken spec
    plain: set[str] = {"json"}
    named: dict[str, set[str]] = {}
    bodies: list[str] = []
    for mod in _BUNDLE_MODULES:
        text = (_HERE / f"{mod}.py").read_text(encoding="utf-8")
        text = text.replace("from __future__ import annotations\n", "")
        text = _SIBLING_IMPORT.sub("", text)
        if mod == "spec":
            text = text[: text.index("def load_spec")]  # the YAML loader is the one part that needs a dependency
        text = _DOCSTRING.sub("", text, count=1)  # each module's docstring; the bundle has one header
        for line in _STD_IMPORT.findall(text):
            if line.startswith("import "):
                plain.add(line.split()[1])
            else:
                _, module, _, names = line.split(None, 3)
                named.setdefault(module, set()).update(n.strip() for n in names.split(","))
        plain.discard("yaml")
        text = _STD_IMPORT.sub("", text)
        bodies.append(f"\n# {'-' * 64} {mod}\n{text.strip(chr(10))}\n")
    code = "".join(bodies)
    lines = [f"import {m}" for m in sorted(plain)]
    for module in sorted(named):
        used = sorted(n for n in named[module] if re.search(rf"\b{re.escape(n)}\b", code))
        if used:
            lines.append(f"from {module} import {', '.join(used)}")
    header = (
        '"""Generated by `siliconforge isa gen`: assembler, golden model and timing checker for this ISA.\n\n'
        'Standard library only. Do not edit; regenerate from isa.yaml."""\n'
        "from __future__ import annotations\n\n" + "\n".join(lines) + "\n"
    )
    tail = (
        f"\n\nSPEC_DICT = json.loads({json.dumps(json.dumps(raw))})\n\n\n"
        "def load() -> IsaSpec:\n    return parse_spec(SPEC_DICT)\n\n\n"
        "def assemble(source: str) -> Program:\n    return Assembler(load()).assemble(source)\n"
    )
    return header + code + tail


def generate_all(spec_path: str | Path, out_dir: str | Path) -> list[Path]:
    """Write every derived artifact; returns the files written."""
    spec = load_spec(spec_path)
    out = Path(out_dir)
    decoder = verilog_decoder(spec)
    files: dict[Path, str] = {
        out / "rtl" / f"{spec.name}_isa.vh": verilog_header(spec),
        out / "rtl" / f"{spec.name}_decode.v": decoder,
        out / "tools" / f"{spec.name}_isa.py": bundle_source(spec_path),
        out / "docs" / "isa.md": isa_markdown(spec),
    }
    sv, sby = decoder_formal(spec)
    files[out / "formal" / f"{spec.name}_decode_check.sv"] = sv
    files[out / "formal" / f"{spec.name}_decode.sby"] = sby
    files[out / "formal" / f"{spec.name}_decode.v"] = decoder  # beside the harness, so `sby` finds both sources
    for i in spec.instructions:
        files[out / "docs" / "isa" / f"{i.name}.svg"] = encoding_svg(spec, i)
    for path, text in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
    return list(files)



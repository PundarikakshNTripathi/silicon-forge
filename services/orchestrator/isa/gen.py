_COLORS = {"fixed": "#2b3a42", "operand": "#c9532b", "unused": "#9aa5ab"}


def encoding_svg(spec: IsaSpec, instr: Instruction) -> str:
    """One row of bit cells, MSB first: fixed bits are dark, operand fields are outlined and named, unused bits are pale."""
    bits = "".join(instr.pattern.split())
    cell, pad = 26, 8
    width = spec.word_bits * cell + 2 * pad
    parts = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="62" viewBox="0 0 {width} 62" '
             f'font-family="ui-monospace,Consolas,monospace" font-size="12" role="img" aria-label="{instr.name} encoding">']
    i = 0
    while i < len(bits):
        ch = bits[i]
        j = i
        if ch.isalpha():
            while j + 1 < len(bits) and bits[j + 1] == ch:
                j += 1
        kind = "operand" if ch.isalpha() else ("unused" if ch == "-" else "fixed")
        x, w = pad + i * cell, (j - i + 1) * cell
        msb, lsb = spec.word_bits - 1 - i, spec.word_bits - 1 - j
        label = f"{msb}" if msb == lsb else f"{msb}:{lsb}"
        if kind == "operand":
            op = next(o for o in instr.operands if o.letter == ch)
            parts.append(f'<rect x="{x}" y="20" width="{w}" height="30" rx="3" fill="none" stroke="{_COLORS[kind]}" '
                         f'stroke-width="1.5"/><text x="{x + w / 2}" y="40" text-anchor="middle" fill="{_COLORS[kind]}">'
                         f'{op.name}</text>')
            parts.append(f'<text x="{x + w / 2}" y="14" text-anchor="middle" fill="#6b7780" font-size="10">{label}</text>')
        else:
            for k in range(i, j + 1):
                xx = pad + k * cell
                solid = kind == "fixed"
                parts.append(f'<rect x="{xx}" y="20" width="{cell}" height="30" fill="{_COLORS[kind]}" '
                             f'fill-opacity="{0.9 if solid else 0.25}" stroke="#fff"/>'
                             f'<text x="{xx + cell / 2}" y="40" text-anchor="middle" fill="#fff">{bits[k] if solid else ""}</text>')
                parts.append(f'<text x="{xx + cell / 2}" y="14" text-anchor="middle" fill="#6b7780" font-size="10">'
                             f'{spec.word_bits - 1 - k}</text>')
        i = j + 1
    parts.append("</svg>")
    return "".join(parts)


def isa_markdown(spec: IsaSpec, svg_dir: str = "isa") -> str:
    out = [f"# {spec.title} instruction set", ""]
    if spec.description:
        out += [spec.description, ""]
    out += [f"{spec.word_bits}-bit fixed-width instructions. This document is generated from `isa.yaml`; the assembler, "
            "disassembler, Verilog decoder and golden model are generated from the same file.", "",
            "## Summary", "", "| Instruction | Syntax | Cycles | Pin event | Encoding |", "|---|---|---|---|---|"]
    for i in spec.instructions:
        out.append(f"| `{i.name}` | `{i.asm}` | {i.cycles} | {'yes' if i.pin_event else ''} | `{''.join(i.pattern.split())}` |")
    out += ["", "## State", "", "| Register | Bits | Reset |", "|---|---:|---:|"]
    out += [f"| `{v.name}` | {v.width} | {v.reset} |" for v in spec.state]
    out += ["", "## Instructions", ""]
    for i in spec.instructions:
        out += [f"### `{i.name}`", "", f"![{i.name} encoding]({svg_dir}/{i.name}.svg)", ""]
        if i.doc:
            out += [i.doc, ""]
        out += [f"Syntax: `{i.asm}`. Takes {i.cycles} cycle(s)."]
        for o in i.operands:
            extra = f" One of: {', '.join(f'`{k}`={v}' for k, v in (o.enum or {}).items())}." if o.enum else ""
            out.append(f"- `{o.name}` ({o.field.width} bits, bits {o.field.msb}:{o.field.lsb}, {o.kind}).{extra} {o.doc}".rstrip())
        flow = i.flow["kind"]
        if flow != "seq":
            out.append(f"- Control flow: {flow}.")
        out.append("")
    return "\n".join(out)

"""Generators: Verilog decoder, formal decoder check, ISA reference (Markdown + bit-field SVGs).

Output is Verilog-2001, not SystemVerilog packages, so it drops into any Yosys/LibreLane flow unchanged.
"""
from __future__ import annotations

from services.orchestrator.isa.spec import Instruction, IsaSpec

BANNER = "// Generated by `siliconforge isa gen` from isa.yaml. Do not edit: change the spec and regenerate."


def _hex(value: int, bits: int) -> str:
    return f"{bits}'h{value:0{(bits + 3) // 4}x}"


def _id(name: str) -> str:
    return name.lower()


def verilog_header(spec: IsaSpec) -> str:
    n = spec.name
    out = [BANNER, f"`ifndef {n.upper()}_ISA_VH", f"`define {n.upper()}_ISA_VH", "",
           f"localparam {n.upper()}_WORD_BITS = {spec.word_bits};", ""]
    for ename, vals in spec.enums.items():
        width = max(1, max(vals.values()).bit_length())
        for k, v in vals.items():
            out.append(f"localparam [{width - 1}:0] {n.upper()}_{ename.upper()}_{k.upper()} = {width}'d{v};")
        out.append("")
    out.append("// operand extraction: `NAME_OPERAND(instruction_word)")
    for i in spec.instructions:
        for o in i.operands:
            out.append(f"`define {n.upper()}_{_id(i.name).upper()}_{o.name.upper()}(w) "
                       f"(w[{o.field.msb}:{o.field.lsb}])")
    out += ["", "`endif", ""]
    return "\n".join(out)


def verilog_decoder(spec: IsaSpec) -> str:
    n = spec.name
    w = spec.word_bits
    ports = ",\n".join(f"    output wire is_{_id(i.name)}" for i in spec.instructions)
    body = []
    for i in spec.instructions:
        body.append(f"  assign is_{_id(i.name)} = (instr & {_hex(i.mask, w)}) == {_hex(i.match, w)};  // {i.pattern.strip()}")
    any_hit = " | ".join(f"is_{_id(i.name)}" for i in spec.instructions) or "1'b0"
    return "\n".join([
        BANNER, "`default_nettype none", "",
        f"module {n}_decode (", f"    input  wire [{w - 1}:0] instr,", ports + ",", "    output wire illegal", ");",
        *body, f"  assign illegal = ~({any_hit});", "endmodule", "`default_nettype wire", "",
    ])


def decoder_formal(spec: IsaSpec) -> tuple[str, str]:
    """(sv, sby): prove the generated decoder is one-hot and that `illegal` is exactly 'no instruction matched'."""
    n = spec.name
    w = spec.word_bits
    names = [f"is_{_id(i.name)}" for i in spec.instructions]
    wires = "\n".join(f"  wire {x};" for x in names)
    conns = ", ".join(f".{x}({x})" for x in names)
    vec = "{" + ", ".join(names) + "}"
    sv = f"""// Generated: formal check of {n}_decode.
module {n}_decode_check (input wire [{w - 1}:0] instr);
{wires}
  wire illegal;
  {n}_decode dut (.instr(instr), {conns}, .illegal(illegal));
  wire [{len(names) - 1}:0] hits = {vec};
  always @* begin
    assert ((hits & (hits - 1'b1)) == 0);       // at most one instruction matches any word
    assert (illegal == (hits == 0));            // illegal means exactly: nothing matched
  end
endmodule
"""
    sby = f"""[tasks]
prove

[options]
mode prove

[engines]
abc pdr

[script]
read -formal {n}_decode.v
read -formal {n}_decode_check.sv
prep -top {n}_decode_check

[files]
{n}_decode.v
{n}_decode_check.sv
"""
    return sv, sby



"""Write the web and TUI colour tokens from configs/design/tokens.json (the single source). `--check` fails if they are stale."""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "configs" / "design" / "tokens.json"
CSS = ROOT / "services" / "dashboard" / "src" / "tokens.css"
PY = ROOT / "services" / "tui" / "tokens.py"
HEADER = "Generated by scripts/gen_tokens.py from configs/design/tokens.json. Edit the JSON, not this file."


def css_block(sel: str, t: dict, mode: str) -> str:
    lines = [f"  --{k}: {v};" for k, v in t[mode].items()]
    lines += [f"  --layer-{k}: {v[mode]};" for k, v in t["layers"].items()]
    return f"{sel} {{\n" + "\n".join(lines) + f"\n  color-scheme: {mode};\n}}\n"


def build_css(t: dict) -> str:
    dark = css_block(':root[data-theme="dark"]', t, "dark")
    auto = css_block(':root:not([data-theme="light"])', t, "dark").replace("\n  ", "\n    ").replace("{\n    ", "{\n    ", 1)
    return (f"/* {HEADER} */\n" + css_block(":root", t, "light") + "\n" + dark
            + "\n@media (prefers-color-scheme: dark) {\n  " + auto.replace("\n", "\n  ").rstrip() + "\n}\n")


def build_py(t: dict) -> str:
    out = ["# SPDX-License-Identifier: AGPL-3.0-or-later", f'"""{HEADER}"""', "from __future__ import annotations", "", "LAYERS = {"]
    for k, v in t["layers"].items():
        out.append(f'    "{k}": {{"label": {v["label"]!r}, "light": "{v["light"]}", "dark": "{v["dark"]}"}},')
    out += ["}", "", "THEMES = {"]
    for mode in ("light", "dark"):
        out.append(f'    "{mode}": {{')
        out += [f'        "{k}": "{v}",' for k, v in t[mode].items()]
        out.append("    },")
    out += ["}", ""]
    return "\n".join(out)


def main(argv: list[str]) -> int:
    t = json.loads(SRC.read_text(encoding="utf-8"))
    want = {CSS: build_css(t), PY: build_py(t)}
    if "--check" in argv:
        stale = [str(p.relative_to(ROOT)) for p, text in want.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
        if stale:
            print("stale (run python scripts/gen_tokens.py):", ", ".join(stale))
            return 1
        return 0
    for p, text in want.items():
        p.write_text(text, encoding="utf-8", newline="\n")
        print("wrote", p.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

"""Third-party license notices for SiliconForge's direct dependencies, read from installed metadata (not from memory).

    python scripts/notices.py            # (re)write THIRD_PARTY_NOTICES.md
    python scripts/notices.py --check    # exit 1 if a direct dependency has an unknown or incompatible license (CI)

Only direct dependencies are listed: those declared in pyproject.toml and services/dashboard/package.json.
"""
from __future__ import annotations

import json
import re
import sys
import tomllib
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
# licenses that may be combined with an AGPL-3.0-or-later work (substring match on the declared license text)
OK = ("MIT", "BSD", "Apache", "ISC", "PSF", "Python Software Foundation", "HPND", "MPL", "LGPL", "OFL", "Unlicense",
      "AGPL", "Zlib", "0BSD", "CC0", "Historical Permission")
EXTERNAL_TOOLS = (
    "Yosys, SymbiYosys, Verilator, OpenROAD, LibreLane, KLayout, Magic, Netgen, Icarus Verilog, cocotb, llama.cpp and the "
    "Antigravity CLI are run as separate programs. They are not bundled in the source tree and keep their own licenses."
)


def _name(req: str) -> str:
    return re.split(r"[<>=!~\[; ]", req.strip(), maxsplit=1)[0]


def py_license(name: str) -> str | None:
    try:
        md = metadata.metadata(name)
    except metadata.PackageNotFoundError:
        return None
    expr = md.get("License-Expression")
    if expr:
        return expr
    lic = (md.get("License") or "").strip()
    if lic and len(lic) < 80 and "\n" not in lic:
        return lic
    classes = [c.split("::")[-1].strip() for c in md.get_all("Classifier") or [] if c.startswith("License ::")]
    return "; ".join(classes) or lic.splitlines()[0][:80] if (classes or lic) else "UNKNOWN"


def python_deps() -> list[tuple[str, str | None]]:
    proj = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))["project"]
    names = {_name(r) for r in proj.get("dependencies", [])}
    for extra in proj.get("optional-dependencies", {}).values():
        names |= {_name(r) for r in extra}
    return [(n, py_license(n)) for n in sorted(names, key=str.lower)]


def node_deps() -> list[tuple[str, str | None]]:
    out = []
    for pkg_json, nm in ((ROOT / "services/dashboard/package.json", ROOT / "services/dashboard/node_modules"),
                         (ROOT / "apps/desktop/package.json", ROOT / "apps/desktop/node_modules")):
        if not pkg_json.exists():
            continue
        pj = json.loads(pkg_json.read_text(encoding="utf-8"))
        for n in sorted({*pj.get("dependencies", {}), *pj.get("devDependencies", {})}, key=str.lower):
            f = nm / n / "package.json"
            lic = None
            if f.exists():
                v = json.loads(f.read_text(encoding="utf-8")).get("license")
                lic = v if isinstance(v, str) else (v or {}).get("type") if v else None
            out.append((n, lic))
    return out


def compatible(lic: str | None) -> bool:
    return bool(lic) and any(k.lower() in lic.lower() for k in OK)


def render(py, node) -> str:
    def table(rows):
        return "\n".join(f"| {n} | {lic or 'not installed here'} |" for n, lic in rows)
    return (
        "# Third-party notices\n\n"
        "Generated by `scripts/notices.py` from installed package metadata. Direct dependencies only.\n"
        "SiliconForge itself is AGPL-3.0-or-later; every license below can be combined with it.\n\n"
        f"## Python\n\n| Package | License |\n| --- | --- |\n{table(py)}\n\n"
        f"## JavaScript (dashboard and desktop shell)\n\n| Package | License |\n| --- | --- |\n{table(node)}\n\n"
        "The two bundled typefaces (Atkinson Hyperlegible Next, Commit Mono) come from the `@fontsource` packages above and are\n"
        "licensed under the SIL Open Font License 1.1, which permits bundling with software.\n\n"
        f"## External tools\n\n{EXTERNAL_TOOLS}\n"
    )


def main() -> int:
    py, node = python_deps(), node_deps()
    if "--check" in sys.argv:
        bad = [(n, lic) for n, lic in py + node if lic is not None and not compatible(lic)]
        for n, lic in bad:
            print(f"license not on the AGPL-compatible allowlist: {n}: {lic}")
        return 1 if bad else 0
    (ROOT / "THIRD_PARTY_NOTICES.md").write_text(render(py, node), encoding="utf-8")
    print(f"wrote THIRD_PARTY_NOTICES.md ({len(py)} python, {len(node)} node)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
